import { mkdirSync, writeFileSync } from "node:fs";
import { renderMarkdown } from "../src/lib/markdown";
import { EMAIL, posts, publications } from "./seed-content";

const MEDIA_ORIGIN = "https://media.oylab.uz";
const NOW = Date.UTC(2026, 10, 4, 12, 0);

const q = (value: string | number | null) =>
  value === null ? "NULL" : typeof value === "number" ? String(value) : `'${value.replace(/'/g, "''")}'`;

async function main() {
  const lines: string[] = ["-- Generated by scripts/build-seed.ts. Do not edit by hand.", "PRAGMA foreign_keys = ON;"];

  for (const post of posts) {
    lines.push(
      `INSERT OR REPLACE INTO posts (id, slug, primary_locale, status, published_at, cover_media_id, created_at, updated_at, updated_by) VALUES (${q(post.id)}, ${q(post.slug)}, ${q(post.primaryLocale)}, 'published', ${post.publishedAt}, NULL, ${NOW}, ${NOW}, ${q(EMAIL)});`,
    );
    for (const t of post.translations) {
      const { html, readingMinutes } = await renderMarkdown(t.bodyMd, { mediaOrigin: MEDIA_ORIGIN });
      lines.push(
        `INSERT OR REPLACE INTO post_translations (post_id, locale, title, summary, body_md, body_html, reading_minutes, updated_at) VALUES (${q(post.id)}, ${q(t.locale)}, ${q(t.title)}, ${q(t.summary)}, ${q(t.bodyMd)}, ${q(html)}, ${readingMinutes}, ${NOW});`,
      );
    }
  }

  for (const pub of publications) {
    lines.push(
      `INSERT OR REPLACE INTO publications (id, slug, primary_locale, status, published_at, year, venue, authors_json, pdf_url, arxiv_url, code_url, doi, bibtex, created_at, updated_at, updated_by) VALUES (${q(pub.id)}, ${q(pub.slug)}, 'en', 'draft', NULL, ${pub.year}, ${q(pub.venue)}, ${q(JSON.stringify(pub.authors))}, NULL, NULL, NULL, NULL, NULL, ${NOW}, ${NOW}, ${q(EMAIL)});`,
    );
    const { html } = await renderMarkdown(pub.abstractMd, { mediaOrigin: MEDIA_ORIGIN });
    lines.push(
      `INSERT OR REPLACE INTO publication_translations (publication_id, locale, title, abstract_md, abstract_html, updated_at) VALUES (${q(pub.id)}, 'en', ${q(pub.title)}, ${q(pub.abstractMd)}, ${q(html)}, ${NOW});`,
    );
  }

  mkdirSync("seeds", { recursive: true });
  writeFileSync("seeds/seed.sql", lines.join("\n") + "\n");
  console.log(`seeds/seed.sql: ${posts.length} posts, ${publications.length} publications`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
